# FSM-состояния диалога заявки.
# FSM (машина состояний) — способ вести пошаговый диалог: бот запоминает,
# на каком шаге находится каждый пользователь, и по-разному реагирует
# на сообщения в зависимости от текущего шага. Похоже на стадии диалога
# в Pawn, только aiogram хранит состояние за тебя (по умолчанию в памяти).

from aiogram.fsm.state import State, StatesGroup


class OrderForm(StatesGroup):
    name = State()     # ждём имя
    phone = State()    # ждём телефон
    task = State()     # ждём описание задачи
    confirm = State()  # показали собранное, ждём подтверждения
